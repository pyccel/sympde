"""Public user-facing API for SymPDE.

This module is the one supported location for convenient, flat imports such
as::

    from sympde.api import BilinearForm, Square, elements_of, grad

It contains the objects used by the projects that depend on SymPDE (PSYDAC,
IGA-Python and GeLaTo) and by the SymPDE documentation. Every object is
imported from the module that defines it.

Internal SymPDE code and the unit tests import objects from their defining
modules instead, to keep their dependencies explicit.
"""

